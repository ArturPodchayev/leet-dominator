class Solution {
public:
    long long countCommas(long long n) {

        if(n==1e15){
            return  5 + (999999999999999 - 1000000000000 +1)*4 + (999999999999-1000000000 +1)*3 + (999999999-1000000+1)*2 + (999999-1000+1)*1;

        }else if(n>=1000000000000 && n<=999999999999999){

            return (n - 1000000000000+1)*4 + (999999999999-1000000000+1)*3 + (999999999-1000000+1)*2 + (999999-1000+1)*1;
        }else if(n>=1000000000 && n<= 999999999999){

            return (n-1000000000+1)*3 + (999999999-1000000+1)*2 + (999999-1000+1)*1;

        }else if(n>=1000000 && n<=999999999){
            return (n-1000000+1)*2 + (999999-1000+1)*1;
        }else if(n>=1000 && n<=999999){
            return (n-1000+1)*1;
        }
        
        return 0;
    }
};
