public class Solution {
    public long CountCommas(long n) {
        if(n<1000) return 0;
        long Count=0L;
        if(n<=999_999){
            return n-999;
        }
        else if(n<=999_999_999){
            Count+=(n-999_999)*2+(999_999-999);
        }else if(n<= 999_999_999_999){
            Count+=((n-999_999_999)*3)+((999_999_999-999_999)*2+(999_999-999));
        }else if(n<=999_999_999_999_999){
            Count+=((n-999_999_999_999)*4)+((999_999_999_999-999_999_999)*3)+((999_999_999-999_999)*2+(999_999-999));
        }else if(n<=1_000_000_000_000_000){
            Count+=((1_000_000_000_000_000-999_999_999_999)*4)+((999_999_999_999-999_999_999)*3)+((999_999_999-999_999)*2+(999_999-999))+1;
        }
        return (long)Count;
    }
}
